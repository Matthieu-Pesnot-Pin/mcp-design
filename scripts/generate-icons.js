#!/usr/bin/env node
/**
 * Fige la bibliotheque d'icones dans `shared/icons/` a partir de `lucide-static`.
 *
 * Les fichiers produits sont commites : ni le serveur MCP publie, ni le bundle
 * de la GUI ne dependent de lucide a l'execution, et la geometrie d'un design
 * ne peut pas changer sous les pieds de l'utilisateur au gre d'un `npm install`.
 * Relancer `npm run generate-icons` apres une mise a jour de lucide-static.
 */
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.join(__dirname, '..');
const outDir = path.join(rootDir, 'shared', 'icons');

const iconNodes = require('lucide-static/icon-nodes.json');
const tags = require('lucide-static/tags.json');
const { version } = require('lucide-static/package.json');

/** Attributs de presentation portes par le noeud du design, jamais par l'icone elle-meme. */
const DROPPED_ATTRS = new Set(['stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'class', 'key']);

const names = Object.keys(iconNodes).sort();

const geometry = {};
for (const name of names) {
  geometry[name] = iconNodes[name].map(([tag, attrs]) => {
    const kept = {};
    for (const [attr, value] of Object.entries(attrs ?? {})) {
      if (!DROPPED_ATTRS.has(attr)) kept[attr] = String(value);
    }
    return [tag, kept];
  });
}

/** Mots-cles de recherche : le nom eclate en segments, plus les synonymes de lucide. */
const keywords = {};
for (const name of names) {
  const fromName = name.split('-');
  const merged = [...new Set([...fromName, ...(tags[name] ?? [])])].filter((word) => word.length > 1);
  if (merged.length > 0) keywords[name] = merged;
}

/**
 * Les donnees sont embarquees comme une chaine JSON parsee au premier acces
 * plutot que comme un litteral d'objet : un objet de 1800 entrees coute cher a
 * analyser au demarrage, et le module est charge par le serveur stdio comme par
 * le navigateur.
 */
function moduleSource(header, exports) {
  const body = exports
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(JSON.stringify(value))};`)
    .join('\n\n');
  return `${header}\n${body}\n`;
}

const banner = (what) =>
  `// Auto-generated by scripts/generate-icons.js - do not edit manually.\n` +
  `// ${what}\n` +
  `// Source: lucide-static ${version}, ISC licence (https://lucide.dev).\n`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'icon-data.ts'),
  moduleSource(banner('Geometry of every icon, in the 24x24 grid.'), [
    ['LUCIDE_VERSION', version],
    ['ICON_DATA_JSON', geometry],
  ]),
  'utf8'
);
fs.writeFileSync(
  path.join(outDir, 'icon-keywords.ts'),
  moduleSource(banner('Search keywords per icon. Loaded on demand, never by the renderer.'), [
    ['ICON_KEYWORDS_JSON', keywords],
  ]),
  'utf8'
);

console.log(`Generated ${names.length} icons from lucide-static ${version}`);
console.log(`  ${path.join(outDir, 'icon-data.ts')}`);
console.log(`  ${path.join(outDir, 'icon-keywords.ts')}`);
